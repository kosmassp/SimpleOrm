using System.Text;
using System.Text.RegularExpressions;

namespace SimpleOrm;

/// <summary>
/// The diff generator core (ADR-0017): compares entity metadata (the final truth)
/// against the table's latest committed snapshot and describes the change; the
/// emitters turn it into migration source with a **generated Down** (derived from
/// the snapshot — the owner's "downs come from versioned schemas"). Renames are
/// never inferred: they arrive as explicit declarations. Type or nullability
/// changes are not auto-expressible (<c>DDL-004</c>) — those migrations are written
/// by hand.
/// </summary>
public static class MigrationGenerator
{
    /// <summary>
    /// The ownership line every generated file carries. <c>diff --amend</c>
    /// (ADR-0017 add.3) replaces only files that carry it — a hand-written
    /// version is never overwritten by the tool.
    /// </summary>
    public const string GeneratedMarker = "Generated by simpleorm diff";

    /// <summary>Whether a root source carries the draft marker (Level 3 M5): <c>[Draft]</c> on its class.</summary>
    public static bool HasDraftMarker(string source) => source.Contains("[Draft]", StringComparison.Ordinal);

    private static readonly Regex DialectStamp = new(
        @"Generated by simpleorm diff \(ADR-0017, dialect (?<label>[A-Za-z0-9_-]+)\)", RegexOptions.Compiled);

    /// <summary>Whether the source was written by the generator (carries <see cref="GeneratedMarker"/>).</summary>
    public static bool IsGenerated(string source)
        => source.Contains(GeneratedMarker, StringComparison.Ordinal);

    /// <summary>
    /// The dialect a generated root was rendered for, from its header stamp — or
    /// null for a root generated before dialect stamping existed. Storage types
    /// are dialect-specific, so amending under another dialect refuses.
    /// </summary>
    public static string? GeneratedDialectLabel(string source)
    {
        var match = DialectStamp.Match(source);
        return match.Success ? match.Groups["label"].Value : null;
    }

    public sealed class ColumnSpec(string name, string storageType, bool nullable)
    {
        public string Name { get; } = name;

        public string StorageType { get; } = storageType;

        public bool Nullable { get; } = nullable;
    }

    public sealed class TableDiff
    {
        public bool IsNew { get; init; }

        public List<ColumnSpec> Added { get; } = [];

        public List<ColumnSpec> Removed { get; } = [];

        public List<(string From, string To)> Renamed { get; } = [];

        /// <summary>The indexes to create, as shapes — the emitter renders them through the dialect (ADR-0043).</summary>
        public List<TableSchema.Index> AddedIndexes { get; } = [];

        public List<string> RemovedIndexNames { get; } = [];

        public List<string> Unsupported { get; } = [];

        public bool HasChanges => IsNew || Added.Count > 0 || Removed.Count > 0 || Renamed.Count > 0
            || AddedIndexes.Count > 0 || RemovedIndexNames.Count > 0;
    }

    /// <summary>
    /// Diffs metadata against the latest snapshot (null = new table). Renames: the
    /// explicit <c>--rename</c> pairs plus the model's <c>[RenamedFrom]</c>
    /// declarations (Level 3 M5), old column → new column.
    /// </summary>
    public static TableDiff Diff(
        EntityMap map, IDialect dialect, TableSchema? snapshot, IReadOnlyDictionary<string, string> renames)
        => Diff(
            SchemaSnapshot.FromMap(map, dialect), snapshot, renames,
            map.Properties.Where(p => p.RenamedFrom is not null)
                .GroupBy(p => p.RenamedFrom!, StringComparer.OrdinalIgnoreCase)
                .ToDictionary(g => g.Key, g => g.First().ColumnName, StringComparer.OrdinalIgnoreCase));   // duplicates are MAP-027 at load

    /// <summary>
    /// The shape-vs-shape core: both sides in snapshot form, so the algorithm is
    /// pure data — which is how the conformance diff cases exercise it.
    /// <paramref name="renames"/> are explicit and must hold (an unknown side is
    /// unsupported); <paramref name="declaredRenames"/> come from the model's
    /// <c>[RenamedFrom]</c> and are permanent, so one that the snapshot no
    /// longer matches — the old column gone, or the new one already there —
    /// declares nothing (the rename was applied, or the column is simply new).
    /// </summary>
    public static TableDiff Diff(
        TableSchema currentSchema, TableSchema? snapshot, IReadOnlyDictionary<string, string> renames,
        IReadOnlyDictionary<string, string>? declaredRenames = null)
    {
        if (snapshot is null)
        {
            return new TableDiff { IsNew = true };
        }

        var diff = new TableDiff();
        var old = snapshot.Columns.ToDictionary(
            c => c.Name,
            c => new ColumnSpec(c.Name, c.StorageType, c.Nullable),
            StringComparer.OrdinalIgnoreCase);
        var current = currentSchema.Columns.ToDictionary(
            c => c.Name,
            c => new ColumnSpec(c.Name, c.StorageType, c.Nullable),
            StringComparer.OrdinalIgnoreCase);

        var effective = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var declared in declaredRenames ?? new Dictionary<string, string>())
        {
            // A declaration is a rename only while it can be one: the old column in
            // the snapshot, the new one not yet, and the model no longer mapping the
            // old one (a model that still has it describes two columns, not a rename).
            if (old.ContainsKey(declared.Key) && !old.ContainsKey(declared.Value) && !current.ContainsKey(declared.Key))
            {
                effective[declared.Key] = declared.Value;
            }
        }

        foreach (var explicitRename in renames)
        {
            effective[explicitRename.Key] = explicitRename.Value;   // an explicit flag wins, and must hold
        }

        foreach (var rename in effective.OrderBy(r => r.Key, StringComparer.Ordinal))   // one emitted order in every implementation
        {
            var from = rename.Key;
            var to = rename.Value;
            if (!old.ContainsKey(from))
            {
                diff.Unsupported.Add($"rename {from} -> {to}: '{from}' is not in the snapshot");
                continue;
            }

            if (!current.ContainsKey(to))
            {
                diff.Unsupported.Add($"rename {from} -> {to}: '{to}' is not a mapped column");
                continue;
            }

            diff.Renamed.Add((from, to));
            var renamedOld = old[from];
            old.Remove(from);
            old[to] = new ColumnSpec(to, renamedOld.StorageType, renamedOld.Nullable);
        }

        foreach (var column in current.Values.Where(c => !old.ContainsKey(c.Name)))
        {
            if (!column.Nullable)
            {
                diff.Unsupported.Add(
                    $"add {column.Name}: non-nullable additions need a default/backfill — write the migration by hand");
            }
            else
            {
                diff.Added.Add(column);
            }
        }

        foreach (var column in old.Values.Where(c => !current.ContainsKey(c.Name)))
        {
            diff.Removed.Add(column);
        }

        foreach (var name in current.Keys.Where(old.ContainsKey))
        {
            var before = old[name];
            var after = current[name];
            if (!string.Equals(before.StorageType, after.StorageType, StringComparison.OrdinalIgnoreCase)
                || before.Nullable != after.Nullable)
            {
                diff.Unsupported.Add(
                    $"column {name}: {before.StorageType}{(before.Nullable ? string.Empty : " not null")} -> "
                    + $"{after.StorageType}{(after.Nullable ? string.Empty : " not null")} — write the migration by hand");
            }
        }

        // Indexes match by structure — unique flag plus ordered (column, direction) —
        // never by name (ADR-0017 add.2): indexes get added directly to the database
        // in urgencies, and one that exists under another name is implemented.
        var oldSignatures = new HashSet<string>(snapshot.Indexes.Select(IndexSignature), StringComparer.Ordinal);
        var modelSignatures = new HashSet<string>(currentSchema.Indexes.Select(IndexSignature), StringComparer.Ordinal);
        foreach (var index in currentSchema.Indexes.Where(i => !oldSignatures.Contains(IndexSignature(i))))
        {
            diff.AddedIndexes.Add(index);
        }

        foreach (var index in snapshot.Indexes.Where(i => !modelSignatures.Contains(IndexSignature(i))))
        {
            diff.RemovedIndexNames.Add(index.Name);
        }

        return diff;
    }

    /// <summary>A trigger's change (ADR-0042): the model's declaration against the latest snapshot's, both neutral.</summary>
    public sealed class TriggerDiff
    {
        public bool IsNew { get; init; }

        public bool IsChanged { get; init; }

        public bool IsRemoved { get; init; }

        public bool HasChanges => IsNew || IsChanged || IsRemoved;
    }

    /// <summary>
    /// Diffs a trigger: neither side — nothing; no snapshot — new; no current
    /// declaration — removed (gated by <c>--allow-remove</c>, <c>DDL-003</c>);
    /// both, differing in timing, events, update-of columns, or the
    /// whitespace-normalized body — changed; a layout-only edit of the body
    /// declares nothing. The relation is part of the comparison: a trigger moved
    /// to another table is a change.
    /// </summary>
    public static TriggerDiff DiffTrigger(TriggerSnapshot? current, TriggerSnapshot? snapshot)
    {
        if (current is null && snapshot is null)
        {
            return new TriggerDiff();
        }

        if (snapshot is null)
        {
            return new TriggerDiff { IsNew = true };
        }

        if (current is null)
        {
            return new TriggerDiff { IsRemoved = true };
        }

        var same = current.Definition.SameAs(snapshot.Definition)
            && string.Equals(current.Relation, snapshot.Relation, StringComparison.Ordinal)
            && current.OnView == snapshot.OnView;
        return new TriggerDiff { IsChanged = !same };
    }

    /// <summary>
    /// Emits a trigger step (ADR-0042) from the **literal declaration** — never
    /// <c>CreateTrigger()</c>, which renders from current metadata and would drift
    /// the applied step's checksum when the body changes again. A change opens
    /// with the expected previous declaration (MIG-012 on outside drift); a
    /// removal is a bare drop. No Down — the runner derives the rollback from the
    /// trigger snapshots (ADR-0018). The declaration is dialect-neutral, so the
    /// emitted step is too.
    /// </summary>
    public static string EmitTriggerStep(
        string rootNamespace, Type entityType, Type triggerType,
        long version, string description, TriggerDefinition? current, TriggerDefinition? previous)
    {
        var builder = new StringBuilder();
        builder.Append("namespace ").Append(rootNamespace).Append(".Trigger.").Append(triggerType.Name).AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("/// <summary>Generated by simpleorm diff (ADR-0042): the literal declaration, guarded by the expected previous one (MIG-012 on outside drift); the rollback derives from the snapshots (ADR-0018).</summary>");
        builder.Append("public sealed class V").Append(version.ToString("0000")).Append('_').Append(description)
            .Append(" : TriggerMigration<global::").Append(entityType.FullName)
            .Append(", global::").Append(triggerType.FullName).AppendLine(">");
        builder.AppendLine("{");
        builder.AppendLine("    public override void Action(TriggerActions actions)");
        builder.AppendLine("    {");
        if (previous is not null)
        {
            AppendTriggerAction(builder, "ExpectDefinition", previous);
        }

        if (current is not null)
        {
            AppendTriggerAction(builder, "Recreate", current);
        }
        else
        {
            builder.AppendLine("        actions.DropTrigger();");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendTriggerAction(StringBuilder builder, string method, TriggerDefinition definition)
    {
        builder.Append("        actions.").Append(method).Append("(TriggerTiming.").Append(definition.Timing)
            .Append(", ").Append(string.Join(" | ", definition.EventList().Select(e => "TriggerEvent." + e)))
            .AppendLine(",");
        builder.AppendLine("            \"\"\"");
        foreach (var line in definition.Sql.Trim().Replace("\r", string.Empty).Split('\n'))
        {
            builder.Append("            ").AppendLine(line.TrimEnd());
        }

        builder.Append("            \"\"\"");
        foreach (var column in definition.UpdateOf)
        {
            builder.Append(", \"").Append(column).Append('"');
        }

        builder.AppendLine(");");
    }

    /// <summary>The structural identity of a declared index: unique + ordered columns with direction.</summary>
    internal static string IndexSignature(EntityIndex index)
        => Signature(index.Unique, index.Columns.Select(c => (c.ColumnName, c.Descending)));

    /// <summary>The structural identity of a snapshotted or introspected index.</summary>
    internal static string IndexSignature(TableSchema.Index index)
        => Signature(index.Unique, index.Columns.Select(c => (c.ColumnName, c.Descending)));

    internal static string Signature(bool unique, IEnumerable<(string Column, bool Descending)> columns)
        => (unique ? "unique|" : "plain|")
            + string.Join(",", columns.Select(c =>
                c.Column.ToLowerInvariant() + (c.Descending ? " desc" : string.Empty)));

    /// <summary>Emits the per-object migration step, Down included (derived from the snapshot).</summary>
    public static string EmitTableStep(
        string rootNamespace, Type entityType, EntityMap map, IDialect dialect,
        long version, string description, TableDiff diff)
    {
        var builder = new StringBuilder();
        builder.Append("namespace ").Append(rootNamespace).Append(".Table.").Append(entityType.Name).AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("/// <summary>Generated by simpleorm diff (ADR-0017); no Down — the runner derives the rollback from the snapshots (ADR-0018).</summary>");
        builder.Append("public sealed class V").Append(version.ToString("0000")).Append('_').Append(description)
            .Append(" : TableMigration<global::").Append(entityType.FullName).AppendLine(">");
        builder.AppendLine("{");
        builder.AppendLine("    public override void Action(TableActions actions)");
        builder.AppendLine("    {");
        if (diff.IsNew)
        {
            AppendSqlAction(builder, dialect.CreateTableSql(map));
            foreach (var indexSql in dialect.CreateIndexSql(map))
            {
                AppendSqlAction(builder, indexSql);
            }
        }
        else
        {
            foreach (var (from, to) in diff.Renamed)
            {
                builder.Append("        actions.RenameColumn(\"").Append(from).Append("\", \"").Append(to).AppendLine("\");");
            }

            foreach (var column in diff.Added)
            {
                builder.Append("        actions.AddColumn(\"").Append(column.Name)
                    .Append("\", \"").Append(column.StorageType).AppendLine("\");");
            }

            foreach (var column in diff.Removed)
            {
                builder.Append("        actions.RemoveColumn(\"").Append(column.Name).AppendLine("\");");
            }

            foreach (var index in diff.AddedIndexes)
            {
                AppendSqlAction(builder, dialect.CreateIndexSql(map.RelationName!, index));
            }

            foreach (var name in diff.RemovedIndexNames)
            {
                builder.Append("        actions.DropIndex(\"").Append(name).AppendLine("\");");
            }
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>
    /// Emits a view/materialized-view step from **literal DDL** (never
    /// metadata-rendered, so the applied step's checksum can never drift when the
    /// definition changes again). A change opens with the expected-previous-
    /// definition guard (MIG-012 on outside drift). No Down is emitted — the
    /// runner derives the rollback (guard + drop + previous definition) from the
    /// DDL snapshots (ADR-0018).
    /// </summary>
    public static string EmitViewStep(
        string rootNamespace, Type entityType, string kindFolder, string objectName,
        long version, string description, string createDdl, string? previousDdl)
    {
        var dropSql = (kindFolder == "MaterializedView" ? "drop materialized view if exists " : "drop view if exists ")
            + objectName;
        var builder = new StringBuilder();
        builder.Append("namespace ").Append(rootNamespace).Append('.').Append(kindFolder).Append('.')
            .Append(entityType.Name).AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("/// <summary>Generated by simpleorm diff (ADR-0017): literal DDL, guarded by the expected previous definition (MIG-012 on outside drift); the rollback derives from the snapshots (ADR-0018).</summary>");
        builder.Append("public sealed class V").Append(version.ToString("0000")).Append('_').Append(description)
            .Append(" : ViewMigration<global::").Append(entityType.FullName).AppendLine(">");
        builder.AppendLine("{");
        builder.AppendLine("    public override void Action(ViewActions actions)");
        builder.AppendLine("    {");
        if (previousDdl is not null)
        {
            AppendViewAction(builder, "ExpectDefinition", previousDdl);
            AppendViewAction(builder, "Sql", dropSql);
        }

        AppendViewAction(builder, "Sql", createDdl);
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendViewAction(StringBuilder builder, string method, string sql)
        => builder.Append("        actions.").Append(method).Append("(\"").Append(EscapeLiteral(sql)).AppendLine("\");");

    private static string EscapeLiteral(string sql)
        => sql.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>
    /// Emits the root version composing the steps in the given order. The header
    /// stamps the dialect (<paramref name="dialectLabel"/>, the CLI's
    /// <c>--dialect</c> name): the recorded unit remembers what its storage types
    /// were rendered for, so <c>diff --amend</c> can refuse a dialect switch.
    /// </summary>
    public static string EmitRoot(
        string rootNamespace, long version, IReadOnlyList<string> stepTypeReferences, string dialectLabel, bool draft = false)
    {
        var builder = new StringBuilder();
        builder.Append("namespace ").Append(rootNamespace).AppendLine(";");
        builder.AppendLine();
        builder.Append("/// <summary>Generated by simpleorm diff (ADR-0017, dialect ").Append(dialectLabel)
            .AppendLine("); review the order before committing.</summary>");
        if (draft)
        {
            // The marker the runner refuses to apply (MIG-013): review the version, then delete this line.
            builder.AppendLine("[Draft]   // DRAFT (simpleorm diff --draft): review this version, then remove this attribute");
        }

        builder.Append("public sealed class V").Append(version.ToString("0000")).AppendLine(" : MigrationVersion");
        builder.AppendLine("{");
        builder.AppendLine("    public override void Compose(VersionBuilder version) => version");
        for (var i = 0; i < stepTypeReferences.Count; i++)
        {
            builder.Append("        .Apply<").Append(stepTypeReferences[i]).Append(">()")
                .AppendLine(i == stepTypeReferences.Count - 1 ? ";" : string.Empty);
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendSqlAction(StringBuilder builder, string sql)
    {
        if (!sql.Contains('\n'))
        {
            builder.Append("        actions.Sql(\"").Append(EscapeLiteral(sql)).AppendLine("\");");
            return;
        }

        builder.AppendLine("        actions.Sql(");
        builder.AppendLine("            \"\"\"");
        foreach (var line in sql.Replace("\r", string.Empty).Split('\n'))
        {
            builder.Append("            ").AppendLine(line);
        }

        builder.AppendLine("            \"\"\");");
    }
}
