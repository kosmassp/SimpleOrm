// The shadow round trip (ADR-0043, spec/migrations.md "Dialects", last paragraph): on every dialect a short
// tree — a literal create table with a unique index in the dialect's own SQL, a view step, a literal
// add-column step, a trigger step — is replayed into a throwaway database, and the snapshots the shadow writes
// from history must equal the metadata-side export apart from generatedAt. It is the integrity check between a
// model and its history, now on SQLite, PostgreSQL, and SQL Server alike.

// roundTripWidget is the table: a database-generated key, a string with a Length facet under a unique index,
// a decimal with Precision/Scale, and a nullable column the third version adds.
type roundTripWidget struct {
	ID    int64       `orm:"column,key,generated"`
	Name  string      `orm:"column,length=100"`
	Price orm.Decimal `orm:"column,precision=10,scale=2"`
	Note  *string     `orm:"column"`
}

func (roundTripWidget) Entity() orm.EntityDef {
	return orm.EntityDef{
		Source:   orm.Table("round_trip_widgets"),
		Indexes:  []orm.IndexDef{orm.Index("Name").Unique()},
		Triggers: []orm.TriggerLink{orm.Trigger[roundTripTrigger]()},
	}
}

// roundTripNames is the view over the table.
type roundTripNames struct {
	ID   int64  `orm:"column,key"`
	Name string `orm:"column"`
}

func (roundTripNames) Entity() orm.EntityDef {
	return orm.EntityDef{Source: orm.View("round_trip_widget_names", "select id, name from round_trip_widgets")}
}

// roundTripTrigger is the declaration the trigger step creates.
type roundTripTrigger struct{}

const roundTripTriggerBody = "update round_trip_widgets set name = name where id in (select n.id from {new: id} n);"

func (roundTripTrigger) Trigger() orm.TriggerDef {
	return orm.TriggerDef{Name: "trg_round_trip", Timing: orm.TimingAfter, Events: orm.EventUpdate, SQL: roundTripTriggerBody}
}

// roundTripSQL is the literal SQL of the three raw steps in one dialect's text.
type roundTripSQL struct {
	createTable, createIndex, createView, addColumn string
}

var roundTripSQLByDialect = map[string]roundTripSQL{
	"sqlite": {
		createTable: "create table round_trip_widgets (id INTEGER PRIMARY KEY, name TEXT NOT NULL, price TEXT NOT NULL) STRICT",
		createIndex: "create unique index ix_round_trip_widgets_name on round_trip_widgets (name)",
		createView:  "create view round_trip_widget_names as select id, name from round_trip_widgets",
		addColumn:   "alter table round_trip_widgets add column note TEXT",
	},
	"postgres": {
		createTable: "create table round_trip_widgets (id bigint generated by default as identity primary key, " +
			"name character varying(100) not null, price numeric(10,2) not null)",
		createIndex: `create unique index "ix_round_trip_widgets_name" on "round_trip_widgets" ("name")`,
		createView:  `create or replace view "round_trip_widget_names" as select id, name from round_trip_widgets`,
		addColumn:   `alter table "round_trip_widgets" add column "note" text`,
	},
	"sqlserver": {
		createTable: "create table [round_trip_widgets] ([id] bigint identity(1,1) primary key, " +
			"[name] nvarchar(100) not null, [price] decimal(10,2) not null)",
		createIndex: "create unique index [ix_round_trip_widgets_name] on [round_trip_widgets] ([name])",
		createView:  "create view [round_trip_widget_names] as select id, name from round_trip_widgets",
		addColumn:   "alter table [round_trip_widgets] add [note] nvarchar(max)",
	},
}

var generatedAtField = regexp.MustCompile(`"generatedAt":\s*"[^"]*"`)

func withoutGeneratedAt(content string) string {
	return generatedAtField.ReplaceAllString(strings.TrimSpace(content), `"generatedAt": ""`)
}

// roundTripSet is the four-version tree in one dialect's SQL.
func roundTripSet(t *testing.T, dialectName string) *migrations.Set {
	t.Helper()
	statements, ok := roundTripSQLByDialect[dialectName]
	if !ok {
		t.Fatalf("the round trip has no SQL for dialect %q", dialectName)
	}

	set, err := migrations.NewSet(
		migrations.NewSQLVersion(1, migrations.SQLVersionStep{
			ObjectName: "round_trip_widgets", Description: "create", Up: []string{statements.createTable, statements.createIndex},
		}),
		migrations.NewSQLVersion(2, migrations.SQLVersionStep{
			ObjectName: "round_trip_widget_names", Description: "create_view", Up: []string{statements.createView},
		}),
		migrations.NewSQLVersion(3, migrations.SQLVersionStep{
			ObjectName: "round_trip_widgets", Description: "add_note", Up: []string{statements.addColumn},
		}),
		migrations.NewSQLVersion(4, migrations.SQLVersionStep{
			ObjectName: "trg_round_trip", Description: "create_trigger",
			Trigger: &migrations.TriggerDeclaration{
				Relation: "round_trip_widgets", RelationKind: migrations.RelationKindTable,
				Timing: core.TimingAfter, Events: core.EventUpdate, SQL: roundTripTriggerBody,
			},
		}),
	)
	if err != nil {
		t.Fatalf("build set: %v", err)
	}
	return set
}

func runShadowRoundTrip(t *testing.T, dialect core.Dialect, host migrations.ShadowHost, admin string) {
	t.Helper()
	set := roundTripSet(t, dialect.Name())

	outDir := t.TempDir()
	result, err := migrations.Shadow(context.Background(), migrations.ShadowOptions{
		Dialect: dialect, Host: host, Admin: admin, Set: set,
		Entities: []reflect.Type{reflect.TypeFor[roundTripWidget](), reflect.TypeFor[roundTripNames]()},
		Triggers: []reflect.Type{reflect.TypeFor[roundTripTrigger]()},
		OutDir:   outDir,
	})
	if err != nil {
		t.Fatalf("shadow: %v", err)
	}
	for _, note := range result.Notes {
		if strings.Contains(note, "disagree") {
			t.Errorf("the catalog and the step disagree: %s", note)
		}
	}

	loader := metadata.NewLoader(nil)
	generatedAt := time.Date(2026, 10, 22, 12, 0, 0, 0, time.UTC)
	tableMap, err := loader.Load(reflect.TypeFor[roundTripWidget]())
	if err != nil {
		t.Fatal(err)
	}
	viewMap, err := loader.Load(reflect.TypeFor[roundTripNames]())
	if err != nil {
		t.Fatal(err)
	}
	declaration := migrations.DeclarationFromEntity(tableMap, tableMap.Triggers[0])
	declaration.Dialect = dialect.Name()

	expected := map[string]string{
		filepath.Join("Table", "roundTripWidget", "V0003.schema.json"): migrations.Export(tableMap, dialect, 3, generatedAt),
		filepath.Join("View", "roundTripNames", "V0002.schema.json"): migrations.ExportDDL(
			viewMap.RelationName, dialect.Name(), "view", dialect.CreateViewSQL(viewMap), 2, generatedAt),
		filepath.Join("Trigger", "roundTripTrigger", "V0004.schema.json"): migrations.ExportTrigger(declaration, 4, generatedAt),
	}
	for relative, want := range expected {
		got, err := os.ReadFile(filepath.Join(outDir, relative))
		if err != nil {
			t.Errorf("the shadow wrote no %s: %v", relative, err)
			continue
		}
		if withoutGeneratedAt(string(got)) != withoutGeneratedAt(want) {
			t.Errorf("%s: the history-side snapshot differs from the metadata-side export:\n--- shadow ---\n%s\n--- metadata ---\n%s",
				relative, strings.TrimSpace(string(got)), want)
		}
	}

	// The range form: --from V0003 trusts the committed snapshots at or below 3 — the table, its index, and the
	// view are rendered back through the dialect (CreateTableFromSchemaSQL and friends) and baselined — and only
	// version 4 replays. The regenerated trigger snapshot is the one the full replay wrote.
	triggerFile := filepath.Join(outDir, "Trigger", "roundTripTrigger", "V0004.schema.json")
	if err := os.Remove(triggerFile); err != nil {
		t.Fatal(err)
	}
	ranged, err := migrations.Shadow(context.Background(), migrations.ShadowOptions{
		Dialect: dialect, Host: host, Admin: admin, Set: set,
		Entities: []reflect.Type{reflect.TypeFor[roundTripWidget](), reflect.TypeFor[roundTripNames]()},
		Triggers: []reflect.Type{reflect.TypeFor[roundTripTrigger]()},
		OutDir:   outDir, From: 3,
	})
	if err != nil {
		t.Fatalf("shadow --from V0003: %v", err)
	}
	if len(ranged.WrittenFiles) != 1 || !strings.HasSuffix(ranged.WrittenFiles[0], "V0004.schema.json") {
		t.Errorf("only version 4 should regenerate, wrote %v", ranged.WrittenFiles)
	}
	baselined := strings.Join(ranged.Notes, "\n")
	for _, restored := range []string{"round_trip_widgets restored from V0003", "round_trip_widget_names restored from V0002"} {
		if !strings.Contains(baselined, restored) {
			t.Errorf("the trusted baseline should note %q, notes:\n%s", restored, baselined)
		}
	}
	regenerated, err := os.ReadFile(triggerFile)
	if err != nil {
		t.Fatalf("the range form wrote no trigger snapshot: %v", err)
	}
	if withoutGeneratedAt(string(regenerated)) != withoutGeneratedAt(expected[filepath.Join("Trigger", "roundTripTrigger", "V0004.schema.json")]) {
		t.Errorf("the range form's trigger snapshot differs:\n%s", regenerated)
	}
}

// The command, not just the function: `shadow --dialect postgres --db <admin>` replays a PostgreSQL tree and
// writes stamped snapshots (the CLI hands the admin connection to the dialect's shadow host).
func TestShadowCLI_PostgresLive(t *testing.T) {
	livePostgres.SkipUnlessAvailable(t, "no PostgreSQL server answered (set SIMPLEORM_POSTGRES to an admin connection string)")
	registry := orm.Registry{
		Entities:   []reflect.Type{reflect.TypeFor[roundTripWidget](), reflect.TypeFor[roundTripNames]()},
		Triggers:   []reflect.Type{reflect.TypeFor[roundTripTrigger]()},
		Migrations: roundTripSet(t, "postgres"),
	}
	outDir := t.TempDir()

	var stdout, stderr bytes.Buffer
	args := []string{"shadow", "--dialect", "postgres", "--db", livePostgres.AdminConnectionString(), "--out", outDir}
	if code := cli.Run(context.Background(), registry, args, &stdout, &stderr); code != 0 {
		t.Fatalf("shadow: code=%d stderr=%s stdout=%s", code, stderr.String(), stdout.String())
	}
	table, err := os.ReadFile(filepath.Join(outDir, "Table", "roundTripWidget", "V0003.schema.json"))
	if err != nil {
		t.Fatalf("the command wrote no table snapshot: %v\n%s", err, stdout.String())
	}
	if !strings.Contains(string(table), `"dialect": "postgres"`) || !strings.Contains(string(table), `"numeric(10,2)"`) {
		t.Errorf("the snapshot should be stamped and in PostgreSQL's spellings:\n%s", table)
	}
}

func TestShadowRoundTrip_SQLite(t *testing.T) {
	runShadowRoundTrip(t, sqlite.New(), sqlite.ShadowHost{}, "")
}

func TestShadowRoundTrip_PostgresLive(t *testing.T) {
	livePostgres.SkipUnlessAvailable(t, "no PostgreSQL server answered (set SIMPLEORM_POSTGRES to an admin connection string)")
	runShadowRoundTrip(t, postgres.New(), postgres.ShadowHost{}, livePostgres.AdminConnectionString())
}

func TestShadowRoundTrip_SQLServerLive(t *testing.T) {
	liveSQLServer.SkipUnlessAvailable(t, "no SQL Server answered (set SIMPLEORM_SQLSERVER to a go-mssqldb admin connection string)")
	runShadowRoundTrip(t, sqlserver.New(), sqlserver.ShadowHost{}, liveSQLServer.AdminConnectionString())
}
