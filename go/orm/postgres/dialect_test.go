func TestIsDeclaredTypeCompatible_FollowsTheTableWithBaseNameReduction(t *testing.T) {
	d := postgres.New()
	yes := map[string][]core.ColumnType{
		"integer":                          {core.TypeInt32, core.TypeInt64, core.TypeInt16, core.TypeEnumInt},
		"int4":                             {core.TypeInt32},
		"bigint":                           {core.TypeInt64, core.TypeEnumInt},
		"int8":                             {core.TypeInt64},
		"smallint":                         {core.TypeInt16, core.TypeInt32, core.TypeInt64, core.TypeEnumInt},
		"boolean":                          {core.TypeBool},
		"numeric(10,2)":                    {core.TypeDecimal},
		"money":                            {core.TypeDecimal},
		"double precision":                 {core.TypeDouble},
		"real":                             {core.TypeFloat},
		"text":                             {core.TypeString, core.TypeEnumText},
		"character varying(100)":           {core.TypeString, core.TypeEnumText},
		"character(3)":                     {core.TypeString, core.TypeEnumText},
		"name":                             {core.TypeString},
		"bytea":                            {core.TypeBytes},
		"uuid":                             {core.TypeGUID},
		"timestamp with time zone":         {core.TypeDateTime, core.TypeDateTimeOffset},
		"timestamp(3) with time zone":      {core.TypeDateTime, core.TypeDateTimeOffset},
		"timestamp without time zone":      {core.TypeDateTime},
		"timestamp(6) without time zone":   {core.TypeDateTime},
		"date":                             {core.TypeDateTime, core.TypeDate},
		"time without time zone":           {core.TypeTime},
		"  TIME(3)  WITHOUT   TIME ZONE  ": {core.TypeTime},
	}
	no := map[string][]core.ColumnType{
		"integer":                     {core.TypeBool, core.TypeString, core.TypeDecimal},
		"bigint":                      {core.TypeInt32, core.TypeInt16},
		"boolean":                     {core.TypeInt32},
		"numeric":                     {core.TypeDouble, core.TypeString},
		"text":                        {core.TypeInt32, core.TypeGUID, core.TypeDateTime},
		"name":                        {core.TypeEnumText},
		"uuid":                        {core.TypeString},
		"timestamp without time zone": {core.TypeDateTimeOffset},
		"date":                        {core.TypeDateTimeOffset, core.TypeTime},
		"time without time zone":      {core.TypeDateTime},
		"integer[]":                   {core.TypeInt32},
		"jsonb":                       {core.TypeString},
		"":                            {core.TypeString, core.TypeInt32},
	}
	for declared, tokens := range yes {
		for _, token := range tokens {
			if !d.IsDeclaredTypeCompatible(declared, token) {
				t.Errorf("%q should be compatible with %s", declared, token)
			}
		}
	}
	for declared, tokens := range no {
		for _, token := range tokens {
			if d.IsDeclaredTypeCompatible(declared, token) {
				t.Errorf("%q should not be compatible with %s", declared, token)
			}
		}
	}
}

