func TestUpdateOnlySQL_RendersExactlyTheListedColumnsWithTheVersionRules(t *testing.T) {
	d := postgres.New()
	transactions := sampleMap(t, reflect.TypeFor[sample.Transaction]())
	assertEqual(t, "listed", d.UpdateOnlySQL(transactions, []*core.PropertyMap{transactions.Property("UserID")}),
		`update "transactions" set "user_id" = @user_id, "version" = "version" + 1 where "id" = @id and "version" = @version`)

	users := usersMap()
	var all []*core.PropertyMap
	for _, p := range users.Properties {
		if !p.IsKey && !p.IsVersion && !p.IsGenerated {
			all = append(all, p)
		}
	}
	assertEqual(t, "one renderer", d.UpdateOnlySQL(users, all), d.UpdateSQL(users))
}

func TestDeleteSQL_PlainAndVersionCheckedForms(t *testing.T) {
	d := postgres.New()
	transactions := sampleMap(t, reflect.TypeFor[sample.Transaction]())
	assertEqual(t, "plain", d.DeleteSQL(transactions, false), `delete from "transactions" where "id" = @id`)
	assertEqual(t, "version-checked", d.DeleteSQL(transactions, true),
		`delete from "transactions" where "id" = @id and "version" = @version`)
	assertEqual(t, "no version column", d.DeleteSQL(usersMap(), true), `delete from "users" where "id" = @id`)
	assertEqual(t, "composite key", d.DeleteSQL(userRolesMap(), false),
		`delete from "user_roles" where "user_id" = @user_id and "role_id" = @role_id`)
}

func TestLimitOffsetClause(t *testing.T) {
	d := postgres.New()
	for _, c := range []struct{ limit, offset, want string }{
		{"@l", "@o", "limit @l offset @o"},
		{"@l", "", "limit @l"},
		{"", "@o", "offset @o"},
		{"", "", ""},
	} {
		assertEqual(t, c.limit+"/"+c.offset, d.LimitOffsetClause(c.limit, c.offset), c.want)
	}
}

func TestMigrationActionDDL(t *testing.T) {
	d := postgres.New()
	assertEqual(t, "RenameTableSQL", d.RenameTableSQL("old_name", "new_name"), `alter table "old_name" rename to "new_name"`)
	assertEqual(t, "RenameColumnSQL", d.RenameColumnSQL("users", "old_col", "new_col"),
		`alter table "users" rename column "old_col" to "new_col"`)
	assertEqual(t, "AddColumnSQL nullable", d.AddColumnSQL("users", "bio", "text", true, ""),
		`alter table "users" add column "bio" text`)
	assertEqual(t, "AddColumnSQL not null with default", d.AddColumnSQL("users", "is_deleted", "boolean", false, "false"),
		`alter table "users" add column "is_deleted" boolean not null default false`)
	assertEqual(t, "DropColumnSQL", d.DropColumnSQL("users", "bio"), `alter table "users" drop column "bio"`)
	assertEqual(t, "DropTableSQL", d.DropTableSQL("users"), `drop table "users"`)
	assertEqual(t, "DropIndexSQL", d.DropIndexSQL("users", "ix_users_name"), `drop index "ix_users_name"`)
}

