func sampleMap(t *testing.T, entityType reflect.Type) *core.EntityMap {
	t.Helper()
	m, err := metadata.NewLoader(nil).Load(entityType)
	if err != nil {
		t.Fatalf("load %s: %v", entityType, err)
	}
	return m
}

func assertEqual(t *testing.T, label, got, want string) {
	t.Helper()
	if got != want {
		t.Errorf("%s:\ngot:\n%s\nwant:\n%s", label, got, want)
	}
}

