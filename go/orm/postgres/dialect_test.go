func TestIntrospectionQueriesBindOneRelationParameter(t *testing.T) {
	d := postgres.New()
	for name, sqlText := range map[string]string{
		"columns": d.ColumnsInfoSQL(), "indexes": d.IndexesInfoSQL(), "view definition": d.ViewDefinitionSQL(),
	} {
		placeholders := core.FindPlaceholders(sqlText)
		if len(placeholders) != 1 || placeholders[0] != "relation" {
			t.Errorf("%s: placeholders %v, want [relation]", name, placeholders)
		}
		if !strings.Contains(sqlText, "to_regclass(@relation)") {
			t.Errorf("%s does not resolve the relation with to_regclass", name)
		}
	}
	if !strings.Contains(d.ViewDefinitionSQL(), "pg_get_viewdef(c.oid, true)") {
		t.Errorf("view definition should read pg_get_viewdef: %s", d.ViewDefinitionSQL())
	}

	// The result columns carry the spec's names (spec/dialects.md "Introspection result shapes").
	for query, aliases := range map[string][]string{
		d.ColumnsInfoSQL():    {"as name", "as type", `as "notnull"`, "as pk"},
		d.IndexesInfoSQL():    {"as index_name", `as "unique"`, "as seqno", `as "column"`, `as "desc"`},
		d.ViewDefinitionSQL(): {"as definition"},
	} {
		for _, alias := range aliases {
			if !strings.Contains(query, alias) {
				t.Errorf("introspection query lacks %q:\n%s", alias, query)
			}
		}
	}
}
