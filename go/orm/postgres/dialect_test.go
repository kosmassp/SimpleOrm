func TestCreateIndexSQL_UniqueAndDescendingColumns(t *testing.T) {
	m := usersMap()
	m.Indexes = []*core.EntityIndex{
		{Name: "ix_users_name", Columns: []core.IndexColumn{{ColumnName: "name"}}, Unique: true},
		{Name: "ix_users_id_name", Columns: []core.IndexColumn{{ColumnName: "id", Descending: true}, {ColumnName: "name"}}},
	}
	got := postgres.New().CreateIndexSQL(m)
	want := []string{
		"create unique index if not exists \"ix_users_name\" on \"users\" (\"name\")",
		"create index if not exists \"ix_users_id_name\" on \"users\" (\"id\" desc, \"name\")",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got %q, want %q", got, want)
	}
}

func TestCreateViewSQL_ViewReplacesAndMaterializedViewIfNotExists(t *testing.T) {
	t2 := reflect.TypeFor[struct{ SalesMonth string }]()
	view := core.NewEntityMap(t2, core.RelationView, "monthly_totals", "", "select 1 as sales_month", nil, nil, core.KeyNone, nil, nil)
	assertEqual(t, "view", postgres.New().CreateViewSQL(view),
		"create or replace view \"monthly_totals\" as\nselect 1 as sales_month")

	materialized := core.NewEntityMap(t2, core.RelationMaterializedView, "monthly_totals", "", "select 1 as sales_month", nil, nil, core.KeyNone, nil, nil)
	assertEqual(t, "materialized view", postgres.New().CreateViewSQL(materialized),
		"create materialized view if not exists \"monthly_totals\" as\nselect 1 as sales_month")
}

