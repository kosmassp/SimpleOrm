// --- the trigger read-back --------------------------------------------------------

// renderRows is what TriggerDefinitionSQL reconstructs for a declaration: the two statements CreateTriggerSQL
// rendered (the catalog reproduces them whitespace-collapsed — the read-back normalizes either way).
func renderRows(t *testing.T, definition core.TriggerDefinition) []string {
	t.Helper()
	rows, err := postgres.New().CreateTriggerSQL("widgets", false, definition)
	if err != nil {
		t.Fatal(err)
	}
	return rows
}

func TestReadBackTrigger_InvertsCreateTriggerSQL(t *testing.T) {
	cases := []core.TriggerDefinition{
		{Name: "trg_one", Timing: core.TimingAfter, Events: core.EventUpdate,
			SQL: "insert into log (id, at) select n.id, {now} from {new: id, name} n;"},
		{Name: "trg_many", Timing: core.TimingAfter, Events: core.EventInsert | core.EventUpdate | core.EventDelete,
			SQL: "update widgets set name = name where id in (select o.id from {old: id} o);"},
		{Name: "trg_narrow", Timing: core.TimingAfter, Events: core.EventUpdate | core.EventDelete, UpdateOf: []string{"name", "price"},
			SQL: "update widgets set name = name where id in (select o.id from {old: id} o);"},
		{Name: "trg_before", Timing: core.TimingBefore, Events: core.EventInsert | core.EventUpdate,
			SQL: "select 1 where {now} is not null;"},
	}
	for _, definition := range cases {
		t.Run(definition.Name, func(t *testing.T) {
			declaration, note := postgres.ShadowHost{}.ReadBackTrigger(definition.Name, renderRows(t, definition))
			if declaration == nil {
				t.Fatalf("no declaration read back: %s", note)
			}
			want := &migrations.TriggerDeclaration{
				Name: definition.Name, Relation: "widgets", Timing: definition.Timing, Events: definition.Events,
				UpdateOf: definition.UpdateOf, SQL: definition.SQL,
			}
			if !declaration.SameAs(want) {
				t.Errorf("read back %+v, want %+v", declaration, want)
			}
		})
	}
}

func TestReadBackTrigger_AbsentAndHandWrittenRows(t *testing.T) {
	host := postgres.ShadowHost{}
	if declaration, note := host.ReadBackTrigger("t", nil); declaration != nil || note != "" {
		t.Errorf("no rows is nil with no note, got %+v %q", declaration, note)
	}
	if declaration, note := host.ReadBackTrigger("t", []string{"create trigger weird after insert on x"}); declaration != nil || !strings.Contains(note, "hand-written") {
		t.Errorf("a row off the grammar is a noted skip, got %+v %q", declaration, note)
	}

	// A function whose tail is not the rendering's own is a hand-written body: skipped, not mis-read.
	rows := renderRows(t, core.TriggerDefinition{Name: "trg", Timing: core.TimingAfter, Events: core.EventUpdate, SQL: "select 1;"})
	tampered := []string{strings.Replace(rows[0], "return null;", "return old;", 1), rows[1]}
	if declaration, note := host.ReadBackTrigger("trg", tampered); declaration != nil || note == "" {
		t.Errorf("a function with another tail is a noted skip, got %+v %q", declaration, note)
	}

	// The pair must agree with the declared name.
	if declaration, note := host.ReadBackTrigger("other", rows); declaration != nil || note == "" {
		t.Errorf("rows named for another trigger are a noted skip, got %+v %q", declaration, note)
	}
}

func TestShadowHost_ImplementsTheContractAndTheReadBack(t *testing.T) {
	var host migrations.ShadowHost = postgres.ShadowHost{}
	if _, ok := host.(migrations.TriggerReadBack); !ok {
		t.Error("PostgreSQL's catalog is lossless for triggers: the host should read one back")
	}
}
