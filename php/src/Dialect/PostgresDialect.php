<?php

declare(strict_types=1);

namespace SimpleOrm\Dialect;

use PDO;
use SimpleOrm\Errors\SimpleOrmException;
use SimpleOrm\Metadata\ColumnType;
use SimpleOrm\Metadata\EntityIndex;
use SimpleOrm\Metadata\EntityMap;
use SimpleOrm\Metadata\IndexColumn;
use SimpleOrm\Metadata\KeyStrategy;
use SimpleOrm\Metadata\PropertyMap;
use SimpleOrm\Metadata\RelationKind;
use SimpleOrm\Metadata\TriggerBody;
use SimpleOrm\Metadata\TriggerDefinition;
use SimpleOrm\Metadata\TriggerEvent;
use SimpleOrm\Metadata\TriggerTiming;
use SimpleOrm\Metadata\TriggerTokenKind;
use SimpleOrm\Migrations\TableSchema;
use SimpleOrm\Migrations\TableSchemaIndex;
use SimpleOrm\Migrations\TableSchemaIndexPart;
use SimpleOrm\Query\AnsiSelectRenderer;
use SimpleOrm\Query\SelectAst;

/**
 * PostgreSQL implementation of {@see Dialect} backed by PDO's `pdo_pgsql` driver
 * (ADR-0025, spec/dialects.md). The session, CRUD, criteria rendering, loading, tracking,
 * SchemaGuard and the migration runner work, and since ADR-0043 so does the migration tooling
 * (snapshot, shadow, diff, derived rollbacks, force sync). Every identifier passes through {@see self::quoteIdentifier()}
 * (always double-quoted — reserved-word-proof), the generated key is read back
 * with `returning`, a collection argument binds as one PostgreSQL array literal
 * (`PdoBinder`, spec/dialects.md "Array parameters"), and the migration run lock
 * is a transaction holding `pg_advisory_xact_lock`.
 */
final class PostgresDialect implements Dialect
{
    /** spec/dialects.md "The run lock": the arbitrary-but-fixed advisory key pair (ASCII 'Simp', 'leOr'). */
    private const LOCK_KEY_ONE = 1399418224;

    private const LOCK_KEY_TWO = 1818578802;

    public function name(): string
    {
        return Dialects::POSTGRES;
    }

    /** Takes a `pgsql:` PDO DSN verbatim (CODING-STANDARD §10); credentials ride in the DSN. */
    public function createConnection(string $connectionString): PDO
    {
        $pdo = new PDO($connectionString);
        $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
        $pdo->setAttribute(PDO::ATTR_EMULATE_PREPARES, false);
        $pdo->setAttribute(PDO::ATTR_STRINGIFY_FETCHES, false);
        $pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);

        return $pdo;
    }

    /** Always double-quoted, a `"` doubled (spec/dialects.md "Capability flags"). */
    public function quoteIdentifier(string $identifier): string
    {
        return '"' . str_replace('"', '""', $identifier) . '"';
    }

    public function createTableSql(EntityMap $map): string
    {
        $lines = [];
        foreach ($map->properties as $property) {
            $column = $this->quoteIdentifier($property->columnName);
            if ($map->keyStrategy === KeyStrategy::DatabaseGenerated && $property->key) {
                // "by default", so fixtures may insert explicit keys (spec/dialects.md).
                $lines[] = $column . ' ' . $this->storageType($map, $property) . ' generated by default as identity primary key';
                continue;
            }

            $line = $column . ' ' . $this->storageType($map, $property);
            if (!$property->nullable) {
                $line .= ' not null';
            }

            if ($map->keyStrategy === KeyStrategy::ClientGuid && $property->key) {
                $line .= ' primary key';
            }

            $lines[] = $line;
        }

        if ($map->keyStrategy === KeyStrategy::Natural && $map->keyProperties !== []) {
            $lines[] = 'primary key (' . implode(', ', array_map(
                fn (PropertyMap $k): string => $this->quoteIdentifier($k->columnName),
                $map->keyProperties,
            )) . ')';
        }

        return 'create table if not exists ' . $this->quoteIdentifier((string) $map->relationName)
            . " (\n    " . implode(",\n    ", $lines) . "\n)";
    }

    /** @return list<string> */
    public function createIndexSql(EntityMap $map): array
    {
        return array_map(
            fn (EntityIndex $index): string => 'create ' . ($index->unique ? 'unique ' : '') . 'index if not exists '
                . $this->quoteIdentifier($index->name) . ' on ' . $this->quoteIdentifier((string) $map->relationName)
                . ' (' . implode(', ', array_map(
                    fn (IndexColumn $c): string => $this->quoteIdentifier($c->columnName) . ($c->descending ? ' desc' : ''),
                    $index->columns,
                )) . ')',
            $map->indexes,
        );
    }

    /** `create or replace view` for a view, `create materialized view if not exists` for a materialized one (ADR-0025). */
    public function createViewSql(EntityMap $map): string
    {
        return $this->createViewSqlFromBody(
            (string) $map->relationName,
            (string) $map->definingSql,
            $map->kind === RelationKind::MaterializedView,
        );
    }

    /** The snapshot-driven table DDL (ADR-0043): one generated key inline as `generated by default as identity primary key`, any other key the trailing constraint. */
    public function createTableSqlFromSchema(TableSchema $schema): string
    {
        $lines = [];
        $plainKeys = [];
        $hasGeneratedKey = false;
        foreach ($schema->columns as $column) {
            if ($column->key && $column->generated) {
                $hasGeneratedKey = true;
                $lines[] = $this->quoteIdentifier($column->name) . ' ' . $column->storageType . ' generated by default as identity primary key';

                continue;
            }

            if ($column->key) {
                $plainKeys[] = $this->quoteIdentifier($column->name);
            }

            $lines[] = $this->quoteIdentifier($column->name) . ' ' . $column->storageType . ($column->nullable ? '' : ' not null');
        }

        if ($plainKeys !== [] && !$hasGeneratedKey) {
            $lines[] = 'primary key (' . implode(', ', $plainKeys) . ')';
        }

        return 'create table if not exists ' . $this->quoteIdentifier($schema->name) . " (\n    " . implode(",\n    ", $lines) . "\n)";
    }

    public function createIndexSqlFromSchema(string $table, TableSchemaIndex $index): string
    {
        return 'create ' . ($index->unique ? 'unique ' : '') . 'index if not exists ' . $this->quoteIdentifier($index->name)
            . ' on ' . $this->quoteIdentifier($table) . ' (' . implode(', ', array_map(
                fn (TableSchemaIndexPart $part): string => $this->quoteIdentifier($part->columnName) . ($part->descending ? ' desc' : ''),
                $index->columns,
            )) . ')';
    }

    /** `create or replace view` for a view, `create materialized view if not exists` for a materialized one (ADR-0025). */
    public function createViewSqlFromBody(string $view, string $body, bool $materialized): string
    {
        $head = $materialized ? 'create materialized view if not exists ' : 'create or replace view ';

        return $head . $this->quoteIdentifier($view) . " as\n" . $body;
    }

    public function dropViewSql(string $view, bool $materialized): string
    {
        return ($materialized ? 'drop materialized view if exists ' : 'drop view if exists ') . $this->quoteIdentifier($view);
    }

    /** `pg_get_viewdef` reformats the parse tree: the `MIG-012` guard compares the engine's own two renderings through a probe view. */
    public function viewDefinitionIsVerbatim(): bool
    {
        return false;
    }

    public function insertSql(EntityMap $map): string
    {
        $columns = array_values(array_filter($map->properties, static fn (PropertyMap $p): bool => !$p->generated));
        $sql = 'insert into ' . $this->quoteIdentifier((string) $map->relationName)
            . ' (' . implode(', ', array_map(fn (PropertyMap $c): string => $this->quoteIdentifier($c->columnName), $columns)) . ')'
            . ' values (' . implode(', ', array_map(static fn (PropertyMap $c): string => '@' . $c->columnName, $columns)) . ')';

        if ($map->keyStrategy === KeyStrategy::DatabaseGenerated) {
            $sql .= ' returning ' . $this->quoteIdentifier($map->keyProperties[0]->columnName);
        }

        return $sql;
    }

    public function updateSql(EntityMap $map): string
    {
        // Generated non-key columns are database-owned: never in SET (mirrors the insert exclusion).
        return $this->renderUpdate($map, array_values(array_filter(
            $map->properties,
            static fn (PropertyMap $p): bool => !$p->key && !$p->version && !$p->generated,
        )));
    }

    public function updateOnlySql(EntityMap $map, array $properties): string
    {
        return $this->renderUpdate($map, $properties);
    }

    /** @param list<PropertyMap> $set */
    private function renderUpdate(EntityMap $map, array $set): string
    {
        $assignments = array_map(
            fn (PropertyMap $p): string => $this->quoteIdentifier($p->columnName) . ' = @' . $p->columnName,
            $set,
        );
        if ($map->versionProperty !== null) {
            $version = $this->quoteIdentifier($map->versionProperty->columnName);
            $assignments[] = $version . ' = ' . $version . ' + 1';
        }

        $sql = 'update ' . $this->quoteIdentifier((string) $map->relationName)
            . ' set ' . implode(', ', $assignments)
            . ' where ' . $this->keyPredicate($map);
        if ($map->versionProperty !== null) {
            $sql .= ' and ' . $this->quoteIdentifier($map->versionProperty->columnName) . ' = @' . $map->versionProperty->columnName;
        }

        return $sql;
    }

    public function deleteSql(EntityMap $map, bool $checkVersion): string
    {
        $sql = 'delete from ' . $this->quoteIdentifier((string) $map->relationName) . ' where ' . $this->keyPredicate($map);
        if ($checkVersion && $map->versionProperty !== null) {
            $sql .= ' and ' . $this->quoteIdentifier($map->versionProperty->columnName) . ' = @' . $map->versionProperty->columnName;
        }

        return $sql;
    }

    public function reportsAffectedRowsBySelect(): bool
    {
        return false;   // the driver's count is the statement's own (ADR-0040 add.3)
    }

    /**
     * Sequential in PHP (ADR-0044, spec/dialects.md "Statement batching"): `pdo_pgsql` refuses several commands in one
     * prepared statement (SQLSTATE 42601) and its emulated form returns only the last result (`nextRowset()` is IM001).
     */
    public function supportsStatementBatching(): bool
    {
        return false;
    }

    public function maxParametersPerMessage(): ?int
    {
        return null;
    }

    private function keyPredicate(EntityMap $map): string
    {
        return implode(' and ', array_map(
            fn (PropertyMap $k): string => $this->quoteIdentifier($k->columnName) . ' = @' . $k->columnName,
            $map->keyProperties,
        ));
    }

    /** spec/dialects.md "Paging clause": plain `limit`/`offset`, and an offset alone needs no `limit`. */
    public function limitOffsetClause(?string $limitParameter, ?string $offsetParameter): string
    {
        return match (true) {
            $limitParameter !== null && $offsetParameter !== null => "limit {$limitParameter} offset {$offsetParameter}",
            $limitParameter !== null => "limit {$limitParameter}",
            $offsetParameter !== null => "offset {$offsetParameter}",
            default => '',
        };
    }

    public function selectSql(SelectAst $select, callable $bindParameter): string
    {
        return AnsiSelectRenderer::selectSql($this, $select, $bindParameter);
    }

    public function pagingRequiresOrderBy(): bool
    {
        return false;
    }

    /** Native row-value membership, `(a, b) in (select …)`. */
    public function supportsRowValueIn(): bool
    {
        return true;
    }

    /** `where id = any(@ids)` — the collection binds as one array literal (spec/dialects.md "Array parameters"). */
    public function supportsArrayParameters(): bool
    {
        return true;
    }

    /**
     * True for the converter's contract (ADR-0025: `timestamptz >= text` refuses). Under PDO's untyped parameters
     * the ISO-8601 string is equivalent — PostgreSQL infers `timestamptz` from the comparison (CODING-STANDARD §10).
     */
    public function bindsTemporalsNatively(): bool
    {
        return true;
    }

    public function supportsMaterializedViews(): bool
    {
        return true;
    }

    /** Declared and dormant: no procedure execution machinery before Level 4. */
    public function supportsProcedures(): bool
    {
        return true;
    }

    public function supportsTransactionalDdl(): bool
    {
        return true;
    }

    /** spec/dialects.md "Introspection result shapes": `pk` is a presence flag on PostgreSQL. */
    public function columnsInfoSql(): string
    {
        return <<<'SQL'
            select a.attname as name,
                   format_type(a.atttypid, a.atttypmod) as type,
                   (case when a.attnotnull then 1 else 0 end)::bigint as "notnull",
                   (case when exists (
                       select 1 from pg_index i
                       where i.indrelid = a.attrelid and i.indisprimary and a.attnum = any(i.indkey)
                   ) then 1 else 0 end)::bigint as pk,
                   (case when a.attidentity in ('a', 'd') then 1 else 0 end)::bigint as generated
            from pg_attribute a
            where a.attrelid = to_regclass(@relation) and a.attnum > 0 and not a.attisdropped
            order by a.attnum
            SQL;
    }

    public function viewDefinitionSql(): string
    {
        return <<<'SQL'
            select pg_get_viewdef(c.oid, true) as definition from pg_class c
            where c.oid = to_regclass(@relation) and c.relkind in ('v', 'm')
            SQL;
    }

    public function indexesInfoSql(): string
    {
        return <<<'SQL'
            select ic.relname as index_name,
                   (case when i.indisunique then 1 else 0 end)::bigint as "unique",
                   k.n::bigint as seqno,
                   a.attname as "column",
                   (case when (i.indoption[k.n] & 1) <> 0 then 1 else 0 end)::bigint as "desc"
            from pg_index i
            join pg_class ic on ic.oid = i.indexrelid
            cross join lateral generate_series(0, i.indnkeyatts - 1) as k(n)
            join pg_attribute a on a.attrelid = i.indrelid and a.attnum = i.indkey[k.n]
            where i.indrelid = to_regclass(@relation)
              and not i.indisprimary
              and not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
            order by ic.relname, k.n
            SQL;
    }

    /** The `VAL-011` table of spec/dialects.md; the declared type is reduced to its base name first. */
    public function isDeclaredTypeCompatible(string $declaredType, ColumnType $type): bool
    {
        $base = self::baseTypeName($declaredType);
        if ($base === '') {
            return false;   // PostgreSQL always declares a type
        }

        return match ($base) {
            'integer', 'int4' => in_array($type, [ColumnType::Int32, ColumnType::Int64, ColumnType::Int16, ColumnType::EnumInt], true),
            'bigint', 'int8' => $type === ColumnType::Int64 || $type === ColumnType::EnumInt,
            'smallint', 'int2' => in_array($type, [ColumnType::Int16, ColumnType::Int32, ColumnType::Int64, ColumnType::EnumInt], true),
            'boolean', 'bool' => $type === ColumnType::Bool,
            'numeric', 'decimal', 'money' => $type === ColumnType::Decimal,
            'double precision', 'float8' => $type === ColumnType::Double,
            'real', 'float4' => $type === ColumnType::Float,
            'text', 'character varying', 'varchar', 'character', 'char' => $type === ColumnType::String || $type === ColumnType::EnumText,
            'name' => $type === ColumnType::String,
            'bytea' => $type === ColumnType::Bytes,
            'uuid' => $type === ColumnType::Guid,
            'timestamp with time zone', 'timestamptz' => $type === ColumnType::DateTime || $type === ColumnType::DateTimeOffset,
            // Type-compatible; the marker rule refuses VAL-020 per value at read time (spec/dialects.md "Temporals").
            'timestamp without time zone', 'timestamp' => $type === ColumnType::DateTime,
            'date' => $type === ColumnType::DateTime || $type === ColumnType::Date,
            'time without time zone', 'time' => $type === ColumnType::Time,
            default => false,
        };
    }

    /** Trimmed, lowercased, parenthesized length/precision removed even mid-name, whitespace collapsed (spec/dialects.md). */
    private static function baseTypeName(string $declaredType): string
    {
        $reduced = (string) preg_replace('/\([^)]*\)/', '', strtolower(trim($declaredType)));

        return trim((string) preg_replace('/\s+/', ' ', $reduced));
    }

    /**
     * Spelled the way `format_type` reports them, so introspected and rendered types compare cleanly (ADR-0043): a
     * `Precision`/`Scale` facet renders `numeric(p,s)`, a `Length` facet `character varying(n)`; `bytea` has no length.
     */
    public function storageType(EntityMap $map, PropertyMap $property): string
    {
        return match ($property->type) {
            ColumnType::Int16 => 'smallint',
            ColumnType::Int32, ColumnType::EnumInt => 'integer',
            ColumnType::Int64 => 'bigint',
            ColumnType::Bool => 'boolean',
            ColumnType::Decimal => $property->precision !== null
                ? 'numeric(' . $property->precision . ',' . ($property->scale ?? 0) . ')'
                : 'numeric',
            ColumnType::Double => 'double precision',
            ColumnType::Float => 'real',
            ColumnType::Guid => 'uuid',
            ColumnType::Bytes => 'bytea',
            ColumnType::DateTime, ColumnType::DateTimeOffset => 'timestamp with time zone',
            ColumnType::Date => 'date',
            ColumnType::Time => 'time without time zone',
            ColumnType::String => $property->length !== null ? 'character varying(' . $property->length . ')' : 'text',
            default => 'text',   // enum_text, JSON and handler (custom) types
        };
    }

    /**
     * One transaction for the whole run, made exclusive by a transaction-scoped advisory lock with a 60 s wait
     * (spec/dialects.md "The run lock"). `BEGIN` goes through `exec` like SQLite's, because the runner ends the
     * run with a raw `COMMIT`/`ROLLBACK`.
     */
    public function beginMigrationRunLock(PDO $connection): void
    {
        $connection->exec('BEGIN');
        $connection->exec(
            "set local lock_timeout = '60s'; select pg_advisory_xact_lock(" . self::LOCK_KEY_ONE . ', ' . self::LOCK_KEY_TWO . ')',
        );
    }

    public function versionTableSql(): string
    {
        return <<<'SQL'
            create table if not exists schema_version (
                version      bigint not null,
                object       text not null,
                description  text not null,
                checksum     text not null,
                applied_at   text not null,
                execution_ms bigint not null,
                primary key (version, object)
            )
            SQL;
    }

    public function renameTableSql(string $fromName, string $toName): string
    {
        return 'alter table ' . $this->quoteIdentifier($fromName) . ' rename to ' . $this->quoteIdentifier($toName);
    }

    public function renameColumnSql(string $table, string $fromName, string $toName): string
    {
        return 'alter table ' . $this->quoteIdentifier($table)
            . ' rename column ' . $this->quoteIdentifier($fromName) . ' to ' . $this->quoteIdentifier($toName);
    }

    public function addColumnSql(string $table, string $column, string $storageType, bool $nullable, ?string $defaultSql): string
    {
        return 'alter table ' . $this->quoteIdentifier($table) . ' add column ' . $this->quoteIdentifier($column) . ' ' . $storageType
            . ($nullable ? '' : ' not null')
            . ($defaultSql === null ? '' : ' default ' . $defaultSql);
    }

    public function dropColumnSql(string $table, string $column): string
    {
        return 'alter table ' . $this->quoteIdentifier($table) . ' drop column ' . $this->quoteIdentifier($column);
    }

    public function dropTableSql(string $table): string
    {
        return 'drop table ' . $this->quoteIdentifier($table);
    }

    /** Index names are schema-scoped on PostgreSQL: the table is not part of the statement. */
    public function dropIndexSql(string $table, string $index): string
    {
        return 'drop index ' . $this->quoteIdentifier($index);
    }

    /**
     * ADR-0042: a PL/pgSQL function `"<name>_fn"()` wrapping the body, then the row-level `create trigger` calling it.
     * An `after` function ends `return null;`; a `before`/`instead of` one returns the row (`old` on delete, else
     * `new`) so the write proceeds. `instead of` exists on views only (`DDL-005` on a table). Events join with `or`,
     * the update carrying `of "a", "b"` natively; `{new: …}`/`{old: …}` expand to a one-row derived table over
     * `new."col"`/`old."col"`, `{now}` to `now()`.
     */
    public function createTriggerSql(string $relation, bool $onView, TriggerDefinition $trigger): array
    {
        if ($trigger->timing === TriggerTiming::InsteadOf && !$onView) {
            throw new SimpleOrmException(
                'DDL-005',
                $trigger->name,
                "PostgreSQL has INSTEAD OF triggers on views only, not on the table '{$relation}'; declare an after or before trigger",
            );
        }

        $body = TriggerBody::expand(
            $trigger->sql,
            $trigger->name,
            fn (TriggerTokenKind $kind, array $columns): string => '(select ' . implode(', ', array_map(
                fn (string $column): string => $kind->value . '.' . $this->quoteIdentifier($column) . ' as ' . $this->quoteIdentifier($column),
                $columns,
            )) . ')',
            'now()',
        );

        $ending = $trigger->timing === TriggerTiming::After
            ? '    return null;'
            : "    if tg_op = 'DELETE' then return old; end if;\n    return new;";
        $function = $this->quoteIdentifier($trigger->name . '_fn');

        $events = array_map(
            fn (TriggerEvent $event): string => $event->value . (
                $event === TriggerEvent::Update && $trigger->updateOf !== []
                    ? ' of ' . implode(', ', array_map($this->quoteIdentifier(...), $trigger->updateOf))
                    : ''
            ),
            $trigger->events,
        );

        return [
            "create or replace function {$function}() returns trigger language plpgsql as \$\$\nbegin\n{$body}\n{$ending}\nend\n\$\$",
            'create trigger ' . $this->quoteIdentifier($trigger->name) . ' ' . $trigger->timing->keyword() . ' '
                . implode(' or ', $events) . ' on ' . $this->quoteIdentifier($relation)
                . " for each row execute function {$function}()",
        ];
    }

    public function dropTriggerSql(string $relation, string $name): array
    {
        return [
            'drop trigger if exists ' . $this->quoteIdentifier($name) . ' on ' . $this->quoteIdentifier($relation),
            'drop function if exists ' . $this->quoteIdentifier($name . '_fn') . '()',
        ];
    }

    /**
     * PostgreSQL has no stored create statement, so both rows are **reconstructed** from the catalog in this dialect's
     * own spelling — the function from `pg_proc.prosrc`, the trigger from `pg_trigger.tgtype`/`tgattr` — such that each,
     * whitespace-collapsed, equals the matching {@see self::createTriggerSql()} statement.
     */
    public function triggerDefinitionSql(): string
    {
        return <<<'SQL'
            select 'create or replace function "' || p.proname || '"() returns trigger language plpgsql as $$' || p.prosrc || '$$' as definition
            from pg_trigger t
            join pg_proc p on p.oid = t.tgfoid
            where t.tgname = @relation and not t.tgisinternal
            union all
            select 'create trigger "' || t.tgname || '" '
                || case when (t.tgtype & 2) <> 0 then 'before' when (t.tgtype & 64) <> 0 then 'instead of' else 'after' end
                || ' '
                || array_to_string(array_remove(array[
                       case when (t.tgtype & 4) <> 0 then 'insert' end,
                       case when (t.tgtype & 16) <> 0 then 'update' || coalesce((
                           select ' of ' || string_agg('"' || a.attname || '"', ', ' order by k.ord)
                           from unnest(t.tgattr::smallint[]) with ordinality as k(attnum, ord)
                           join pg_attribute a on a.attrelid = t.tgrelid and a.attnum = k.attnum), '') end,
                       case when (t.tgtype & 8) <> 0 then 'delete' end], null), ' or ')
                || ' on "' || c.relname || '" for each row execute function "' || p.proname || '"()' as definition
            from pg_trigger t
            join pg_class c on c.oid = t.tgrelid
            join pg_proc p on p.oid = t.tgfoid
            where t.tgname = @relation and not t.tgisinternal
            SQL;
    }
}
