/**
 * Pins every rendered string and flag of {@see PostgresDialect} against
 * spec/dialects.md (ADR-0025) — pure rendering, no database. The `ast/` SELECT
 * pins are the conformance runners' job; this covers the DDL/CRUD/action
 * renderings the spec states in prose. `EntityMap`s are hand-built fixtures, as
 * in {@see SqliteDialectTest}.
 */
final class PostgresDialectTest extends TestCase
{
    private PostgresDialect $dialect;

    protected function setUp(): void
    {
        $this->dialect = new PostgresDialect();
    }

    #[Test]
    public function the_registry_resolves_postgres_by_name(): void
    {
        self::assertContains('postgres', Dialects::names());
        self::assertInstanceOf(PostgresDialect::class, Dialects::create('postgres'));
        self::assertInstanceOf(PostgresDialect::class, Dialects::create(' Postgres '));
    }

    #[Test]
    public function every_capability_flag_matches_the_spec_table(): void
    {
        self::assertFalse($this->dialect->pagingRequiresOrderBy());
        self::assertTrue($this->dialect->supportsRowValueIn());
        self::assertTrue($this->dialect->supportsArrayParameters());
        self::assertTrue($this->dialect->bindsTemporalsNatively());
        self::assertTrue($this->dialect->supportsMaterializedViews());
        self::assertTrue($this->dialect->supportsProcedures());
        self::assertTrue($this->dialect->supportsTransactionalDdl());
        self::assertFalse($this->dialect->reportsAffectedRowsBySelect());
    }

    #[Test]
    public function quote_identifier_always_double_quotes_and_doubles_an_embedded_quote(): void
    {
        self::assertSame('"users"', $this->dialect->quoteIdentifier('users'));
        self::assertSame('"order"', $this->dialect->quoteIdentifier('order'));
        self::assertSame('"we""ird"', $this->dialect->quoteIdentifier('we"ird'));
    }

    #[Test]
    public function create_table_sql_renders_a_database_generated_key_as_identity_by_default(): void
    {
        self::assertSame(
            "create table if not exists \"users\" (\n"
                . "    \"id\" bigint generated by default as identity primary key,\n"
                . "    \"name\" text not null,\n"
                . "    \"email\" text not null,\n"
                . "    \"display_name\" text,\n"
                . "    \"created_at\" timestamp with time zone not null,\n"
                . "    \"updated_at\" timestamp with time zone\n"
                . ')',
            $this->dialect->createTableSql(self::userMap()),
        );
    }

    #[Test]
    public function create_table_sql_renders_a_client_guid_key_as_uuid(): void
    {
        $widget = new class {
            public string $id;
        };

        $map = new EntityMap(
            $widget::class,
            RelationKind::Table,
            'widgets',
            null,
            null,
            [],
            [new PropertyMap(new ReflectionProperty($widget, 'id'), 'id', ColumnType::Guid, 'string', nullable: false, key: true)],
            KeyStrategy::ClientGuid,
            [],
            [],
        );

        self::assertSame(
            "create table if not exists \"widgets\" (\n    \"id\" uuid not null primary key\n)",
            $this->dialect->createTableSql($map),
        );
    }

    #[Test]
    public function create_table_sql_renders_a_natural_composite_key_as_a_trailing_line(): void
    {
        self::assertSame(
            "create table if not exists \"user_roles\" (\n"
                . "    \"user_id\" bigint not null,\n"
                . "    \"role_id\" bigint not null,\n"
                . "    \"granted_by\" text,\n"
                . "    \"created_at\" timestamp with time zone not null,\n"
                . "    \"updated_at\" timestamp with time zone,\n"
                . "    primary key (\"user_id\", \"role_id\")\n"
                . ')',
            $this->dialect->createTableSql(self::userRoleMap()),
        );
    }

    #[Test]
    public function create_index_sql_renders_unique_and_descending_columns(): void
    {
        $users = self::withIndexes(self::userMap(), [
            new EntityIndex('ix_users_email', [new IndexColumn('email', 'email', false)], unique: true),
        ]);
        self::assertSame(
            ['create unique index if not exists "ix_users_email" on "users" ("email")'],
            $this->dialect->createIndexSql($users),
        );

        $transactions = self::withIndexes(self::transactionMap(), [
            new EntityIndex(
                'ix_transactions_status_created',
                [new IndexColumn('status', 'status', false), new IndexColumn('createdAtUtc', 'created_at', true)],
                unique: false,
            ),
        ]);
        self::assertSame(
            ['create index if not exists "ix_transactions_status_created" on "transactions" ("status", "created_at" desc)'],
            $this->dialect->createIndexSql($transactions),
        );
    }

    #[Test]
    public function create_view_sql_replaces_a_view_and_guards_a_materialized_view(): void
    {
        $definition = 'select id from users';

        self::assertSame(
            "create or replace view \"user_ids\" as\n{$definition}",
            $this->dialect->createViewSql(self::viewMap(RelationKind::View, 'user_ids', $definition)),
        );
        self::assertSame(
            "create materialized view if not exists \"user_ids_mv\" as\n{$definition}",
            $this->dialect->createViewSql(self::viewMap(RelationKind::MaterializedView, 'user_ids_mv', $definition)),
        );
    }

    #[Test]
    public function insert_sql_excludes_generated_columns_and_returns_the_quoted_key(): void
    {
        self::assertSame(
            'insert into "users" ("name", "email", "display_name", "created_at", "updated_at") '
                . 'values (@name, @email, @display_name, @created_at, @updated_at) returning "id"',
            $this->dialect->insertSql(self::userMap()),
        );
    }

    #[Test]
    public function insert_sql_has_no_returning_clause_for_a_natural_key(): void
    {
        self::assertSame(
            'insert into "user_roles" ("user_id", "role_id", "granted_by", "created_at", "updated_at") '
                . 'values (@user_id, @role_id, @granted_by, @created_at, @updated_at)',
            $this->dialect->insertSql(self::userRoleMap()),
        );
    }

    #[Test]
    public function update_sql_bumps_the_version_and_requires_it_in_the_where(): void
    {
        self::assertSame(
            'update "transactions" set "user_id" = @user_id, "status" = @status, "amount" = @amount, '
                . '"note" = @note, "created_at" = @created_at, "updated_at" = @updated_at, "version" = "version" + 1 '
                . 'where "id" = @id and "version" = @version',
            $this->dialect->updateSql(self::transactionMap()),
        );
    }

    #[Test]
    public function update_only_sql_renders_exactly_the_listed_columns_with_the_version_rules(): void
    {
        $map = self::transactionMap();
        $amount = $map->property('amount');
        self::assertNotNull($amount);

        self::assertSame(
            'update "transactions" set "amount" = @amount, "version" = "version" + 1 where "id" = @id and "version" = @version',
            $this->dialect->updateOnlySql($map, [$amount]),
        );
    }

    #[Test]
    public function update_sql_without_a_version_column_has_a_plain_key_where(): void
    {
        self::assertSame(
            'update "users" set "name" = @name, "email" = @email, "display_name" = @display_name, '
                . '"created_at" = @created_at, "updated_at" = @updated_at where "id" = @id',
            $this->dialect->updateSql(self::userMap()),
        );
    }

    #[Test]
    public function delete_sql_adds_the_version_predicate_only_when_asked(): void
    {
        self::assertSame(
            'delete from "transactions" where "id" = @id',
            $this->dialect->deleteSql(self::transactionMap(), checkVersion: false),
        );
        self::assertSame(
            'delete from "transactions" where "id" = @id and "version" = @version',
            $this->dialect->deleteSql(self::transactionMap(), checkVersion: true),
        );
    }

    #[Test]
    public function limit_offset_clause_is_plain_limit_and_offset_in_all_three_forms(): void
    {
        self::assertSame('limit @c0 offset @c1', $this->dialect->limitOffsetClause('@c0', '@c1'));
        self::assertSame('limit @c0', $this->dialect->limitOffsetClause('@c0', null));
        self::assertSame('offset @c0', $this->dialect->limitOffsetClause(null, '@c0'));
        self::assertSame('', $this->dialect->limitOffsetClause(null, null));
    }

    #[Test]
    public function version_table_sql_matches_the_spec_ddl_byte_for_byte(): void
    {
        self::assertSame(
            "create table if not exists schema_version (\n"
                . "    version      bigint not null,\n"
                . "    object       text not null,\n"
                . "    description  text not null,\n"
                . "    checksum     text not null,\n"
                . "    applied_at   text not null,\n"
                . "    execution_ms bigint not null,\n"
                . "    primary key (version, object)\n"
                . ')',
            $this->dialect->versionTableSql(),
        );
    }

    #[Test]
    public function migration_action_sql_matches_the_spec_table(): void
    {
        self::assertSame('alter table "users" rename to "people"', $this->dialect->renameTableSql('users', 'people'));
        self::assertSame(
            'alter table "users" rename column "name" to "full_name"',
            $this->dialect->renameColumnSql('users', 'name', 'full_name'),
        );
        self::assertSame(
            'alter table "users" add column "age" integer',
            $this->dialect->addColumnSql('users', 'age', 'integer', nullable: true, defaultSql: null),
        );
        self::assertSame(
            'alter table "users" add column "age" integer not null default 0',
            $this->dialect->addColumnSql('users', 'age', 'integer', nullable: false, defaultSql: '0'),
        );
        self::assertSame('alter table "users" drop column "age"', $this->dialect->dropColumnSql('users', 'age'));
        self::assertSame('drop table "users"', $this->dialect->dropTableSql('users'));
        // Index names are schema-scoped: the table does not appear.
        self::assertSame('drop index "ix_users_email"', $this->dialect->dropIndexSql('users', 'ix_users_email'));
    }

