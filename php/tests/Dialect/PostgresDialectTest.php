    /** @param class-string $class */
    private static function prop(
        string $class,
        string $property,
        string $column,
        ColumnType $type,
        string $phpType,
        bool $nullable = false,
        bool $key = false,
        bool $generated = false,
        bool $version = false,
    ): PropertyMap {
        return new PropertyMap(
            new ReflectionProperty($class, $property),
            $column,
            $type,
            $phpType,
            $nullable,
            $key,
            $generated,
            $version,
        );
    }
